-- Change control for the protocol profile and the model (R-16, R-17).
-- Profile versions stay append-only; they now carry the reason, an approval state and, for rollbacks, the
-- version they copy. A model is "sin evidencia" until a validation report is registered against its sha256.
ALTER TABLE protocol_profiles ADD COLUMN reason VARCHAR(200);
ALTER TABLE protocol_profiles ADD COLUMN reverted_from INTEGER;
ALTER TABLE protocol_profiles ADD COLUMN status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE';
ALTER TABLE protocol_profiles ADD COLUMN decided_by VARCHAR(128);
ALTER TABLE protocol_profiles ADD COLUMN decided_at_epoch_ms BIGINT;
ALTER TABLE protocol_profiles ADD CONSTRAINT chk_protocol_profile_status CHECK (status IN ('ACTIVE', 'PENDING', 'REJECTED'));
UPDATE protocol_profiles SET reason = 'Perfil inicial del proyecto' WHERE reason IS NULL;

CREATE TABLE change_control_settings (
    id SMALLINT PRIMARY KEY,
    second_approver_required BOOLEAN NOT NULL,
    updated_by VARCHAR(128) NOT NULL,
    updated_at_epoch_ms BIGINT NOT NULL CHECK (updated_at_epoch_ms >= 0),
    CONSTRAINT chk_change_control_single CHECK (id = 1)
);
INSERT INTO change_control_settings (id, second_approver_required, updated_by, updated_at_epoch_ms)
VALUES (1, FALSE, 'SYSTEM', 0);

CREATE TABLE model_releases (
    model_sha256 CHAR(64) NOT NULL,
    model_version VARCHAR(128) NOT NULL,
    dataset_version VARCHAR(128) NOT NULL,
    first_seen_epoch_ms BIGINT NOT NULL CHECK (first_seen_epoch_ms >= 0),
    PRIMARY KEY (model_sha256, model_version, dataset_version)
);

CREATE TABLE validation_reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_sha256 CHAR(64) NOT NULL,
    profile_version INTEGER,
    title VARCHAR(120) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    document_sha256 CHAR(64) NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    created_at_epoch_ms BIGINT NOT NULL CHECK (created_at_epoch_ms >= 0)
);
CREATE INDEX idx_validation_reports_model ON validation_reports (model_sha256);
