-- Local ADMIN accounts for on-premises deployments (password + TOTP). The TOTP secret is stored AES-GCM encrypted,
-- the password as a bcrypt hash and session tokens only as SHA-256.
CREATE TABLE admin_accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    totp_secret_enc VARCHAR(200) NOT NULL,
    totp_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    last_totp_step BIGINT NOT NULL DEFAULT 0,
    password_failures INTEGER NOT NULL DEFAULT 0,
    totp_failures INTEGER NOT NULL DEFAULT 0,
    failure_window_start_ms BIGINT,
    locked_until_ms BIGINT,
    created_at_epoch_ms BIGINT NOT NULL,
    disabled BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE admin_sessions (
    token_hash VARCHAR(64) PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES admin_accounts(account_id),
    expires_at_epoch_ms BIGINT NOT NULL
);

CREATE INDEX idx_admin_sessions_expiry ON admin_sessions (expires_at_epoch_ms);
